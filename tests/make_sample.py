"""Generate small synthetic test media with ffmpeg (fully deterministic sources).

Usage:
  python -m myvideoai.tests.make_sample [seconds] [width] [height] [fps]
      -> samples/sample.mp4 and samples/sample_lowres.mp4 (half-res, for upscaling test)

  python -m myvideoai.tests.make_sample --audio
      -> samples/sample_audio.mp4 only (video + AAC sine track)

  python -m myvideoai.tests.make_sample --all
      -> all three samples

All media is synthesised from FFmpeg lavfi sources (testsrc2 / sine), so the
repository ships no third-party footage and every file can be regenerated byte
for byte on any machine with the same FFmpeg build.
"""
from __future__ import annotations

import subprocess
import sys

from ..core.config import SAMPLES_DIR
from ..core.video_io import FFMPEG


def make(seconds=2, w=640, h=360, fps=30):
    """Create sample.mp4 (clean) and sample_lowres.mp4 (degraded half-res)."""
    SAMPLES_DIR.mkdir(parents=True, exist_ok=True)
    full = str(SAMPLES_DIR / "sample.mp4")
    low = str(SAMPLES_DIR / "sample_lowres.mp4")

    # testsrc2 gives moving shapes + gradient -> good for perceptual comparison
    cmd = [FFMPEG, "-y", "-v", "error",
           "-f", "lavfi", "-i", f"testsrc2=size={w}x{h}:rate={fps}:duration={seconds}",
           "-c:v", "libx264", "-crf", "18", "-pix_fmt", "yuv420p", full]
    subprocess.check_call(cmd)

    # a deliberately degraded low-res copy (half size, low quality) to demo restoration
    lw, lh = w // 2, h // 2
    cmd2 = [FFMPEG, "-y", "-v", "error", "-i", full,
            "-vf", f"scale={lw}:{lh},gblur=sigma=0.6",
            "-c:v", "libx264", "-crf", "30", "-pix_fmt", "yuv420p", low]
    subprocess.check_call(cmd2)

    print("created:")
    print(" ", full)
    print(" ", low)
    return full, low


def make_audio(seconds=2, w=320, h=180, fps=30, freq=440):
    """Create sample_audio.mp4: the same synthetic pattern plus an AAC sine track.

    Used to exercise the audio muxing / audio-keep paths without shipping any
    third-party audio asset.
    """
    SAMPLES_DIR.mkdir(parents=True, exist_ok=True)
    out = str(SAMPLES_DIR / "sample_audio.mp4")

    cmd = [FFMPEG, "-y", "-v", "error",
           "-f", "lavfi", "-i", f"testsrc2=size={w}x{h}:rate={fps}:duration={seconds}",
           "-f", "lavfi", "-i", f"sine=frequency={freq}:sample_rate=44100:duration={seconds}",
           "-c:v", "libx264", "-crf", "18", "-pix_fmt", "yuv420p",
           "-c:a", "aac", "-b:a", "128k", "-shortest", out]
    subprocess.check_call(cmd)

    print("created:")
    print(" ", out)
    return out


def make_all(seconds=2, w=640, h=360, fps=30):
    full, low = make(seconds, w, h, fps)
    audio = make_audio(seconds, w // 2, h // 2, fps)
    return full, low, audio


if __name__ == "__main__":
    a = sys.argv[1:]
    if a and a[0] == "--audio":
        make_audio()
    elif a and a[0] == "--all":
        make_all()
    else:
        secs = float(a[0]) if len(a) > 0 else 2
        w = int(a[1]) if len(a) > 1 else 640
        h = int(a[2]) if len(a) > 2 else 360
        fps = int(a[3]) if len(a) > 3 else 30
        make(secs, w, h, fps)
